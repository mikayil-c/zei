#[derive(Clone, Debug)]
pub struct Diagnostic {
    pub kind: DiagnosticKind,
    pub message: String, // Error message
    pub span: Span,      // Range in source code.
}

impl Diagnostic {
    pub fn new(kind: DiagnosticKind, message: String, span: Span) -> Self {
        Self {
            kind,
            message,
            span,
        }
    }
}

#[derive(Clone, Debug, PartialEq)]
pub enum DiagnosticKind {
    Error,
}

// Holding information about where exactly is a Token.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Span {
    pub start: usize,
    pub end: usize,
    pub line: usize,
    pub column: usize,
}

impl Span {
    pub fn new(start: usize, end: usize, line: usize, column: usize) -> Self {
        Self {
            start,
            end,
            line,
            column,
        }
    }
}

#[derive(Clone, Debug)]
pub struct ParseError;

// Generated by AI. Check that code later but not now...
pub fn report_diagnostics(source: &str, diagnostics: &[Diagnostic]) {
    for diag in diagnostics {
        // 1. First, print the error type and message.
        println!(
            "[line {}] {:?}: {}",
            diag.span.line, diag.kind, diag.message
        );

        // 2. Retrieve the exact line containing the error from the original text.
        // Note: Since system starts at line 1, we set the index to -1.
        if let Some(line_text) = source.lines().nth(diag.span.line - 1) {
            // Creating the “ 1 | ” part on the left.
            let line_prefix = format!(" {} | ", diag.span.line);

            // Printing the line itself.
            println!("{}{}", line_prefix, line_text);

            // 3. Calculate the spacing to align the caret (^) in the correct column.
            let padding_spaces = " ".repeat(line_prefix.len() + diag.span.column);

            // Add as many ^ symbols as the length of the error (e.g., the difference between start and end).
            let error_length = diag.span.end.saturating_sub(diag.span.start).max(1);
            let pointers = "^".repeat(error_length);

            // Printing the pointer.
            println!("{}{}", padding_spaces, pointers);
        }

        // Insert a space between errors
        println!();
    }
}
